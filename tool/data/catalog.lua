--[[
  catalog.lua

  Starting descriptions for known effect plugins. Each entry:

    names        plugin names this entry applies to (without vendor). Names
                 are matched after normalization: letter case, channel layout
                 ("Stereo", "(Mono)") and a trailing version are ignored, so
                 "Chorus 4 (Stereo)" and "Chorus 5" both match "Chorus".
    vendor       used only when Renoise reports no vendor
    category     primary category (see data/taxonomy.lua)
    sub          optional sub-category of the primary category
    secondary    optional second category
    tags         need tags (see data/taxonomy.lua)
    description  what it does and when to reach for it, 120 characters at most
    needs_review true when the description is a cautious best guess

  Descriptions are indicative and can be corrected in the browser; user
  edits are stored separately and always win over this file.
  Plugin and vendor names belong to their respective owners.
]]

local function e(names, vendor, category, sub, tags, description, extra)
  local entry = {
    names = type(names) == "table" and names or { names },
    vendor = vendor, category = category, sub = sub or "",
    tags = tags, description = description,
  }
  for key, value in pairs(extra or {}) do
    entry[key] = value
  end
  return entry
end

