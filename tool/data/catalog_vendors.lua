--[[
  catalog_vendors.lua

  More catalog entries, grouped by vendor. Same format and rules as
  data/catalog.lua, with a shorter helper:

    e(names, vendor, category, tags, description, extra)

  extra may set secondary (a second category) and needs_review.
  Descriptions are written for this project, 120 characters at most.
  Plugin and vendor names belong to their respective owners.
]]

local function e(names, vendor, category, tags, description, extra)
  local entry = {
    names = type(names) == "table" and names or { names },
    vendor = vendor, category = category, sub = "",
    tags = tags, description = description,
  }
  for key, value in pairs(extra or {}) do
    entry[key] = value
  end
  return entry
end

local R = { needs_review = true }

local function also(category, review)
  return { secondary = category, needs_review = review or nil }
end

-- Plugins whose name carries a version in the middle ("Ozone 11 Maximizer")
-- are listed once per recent version.
local function versions(prefix, list, suffix)
  local result = {}
  for _, v in ipairs(list) do
    result[#result + 1] = prefix .. " " .. v .. " " .. suffix
  end
  return result
end

